/// Generates `lib/food/known_foods.g.dart` from the Firestore `food`
/// collection, giving every stored food a typed [KnownFood] enum value.
///
/// ```sh
/// dart run tool/generate_food.dart
/// ```
///
/// Step 4 of tool/fill_food_db.dart, which runs the whole pipeline.
library;

import 'dart:io';

import 'package:hackathon/food/food.dart';

import 'src/food_store.dart';

const _output = 'lib/food/known_foods.g.dart';

/// Names an enum value cannot take: Dart reserved words plus members every
/// enum already has.
const _reserved = {
  'assert', 'break', 'case', 'catch', 'class', 'const', 'continue', //
  'default', 'do', 'else', 'enum', 'extends', 'false', 'final', 'finally',
  'for', 'if', 'in', 'is', 'new', 'null', 'rethrow', 'return', 'super',
  'switch', 'this', 'throw', 'true', 'try', 'var', 'void', 'while', 'with',
  'values', 'index', 'name', 'hashCode', 'runtimeType', 'toString',
  'noSuchMethod', 'food', 'id', 'fromId',
};

Future<void> main() async {
  final store = await FoodStore.signIn();
  final foods = (await store.all()).entries.toList()
    ..sort((a, b) => a.key.compareTo(b.key));

  final used = <String>{};
  final values = [
    for (final MapEntry(key: id, value: food) in foods)
      '  ${_identifier(id, used)}(\n'
          '    ${_string(id)},\n'
          '    ${_food(food)},\n'
          '  )',
  ];

  await File(_output).writeAsString('''
// GENERATED by `dart run tool/generate_food.dart` from Firestore `food`.
// Do not edit by hand; re-run the generator after changing the collection.

import 'food.dart';
import 'health_condition.dart';
${foods.any((f) => f.value.nutrients.isNotEmpty) ? "import 'nutrient.dart';\n" : ''}import 'preference.dart';

/// Every food stored in Firestore when this file was generated.
///
/// [Food.localNews] is a snapshot from generation time; use `FoodRepository`
/// for the latest news.
enum KnownFood {
${values.join(',\n')}${values.isEmpty ? '' : ';'}

  const KnownFood(this.id, this.food);

  /// Firestore document ID, as in `food/{id}`.
  final String id;

  final Food food;

  static final Map<String, KnownFood> _byId = {
    for (final f in values) f.id: f,
  };

  /// The food stored as [id], or null if it was added after generation.
  static KnownFood? fromId(String id) => _byId[id];

  /// The food called [name], matched the same way as Firestore IDs.
  static KnownFood? fromName(String name) => _byId[Food.idFor(name)];
}
''');

  final format = await Process.run('dart', ['format', _output]);
  if (format.exitCode != 0) stderr.write(format.stderr);
  stdout.writeln('Wrote ${foods.length} foods to $_output.');
}

String _food(Food f) =>
    'Food(name: ${_string(f.name)}, '
    'alternatives: {${f.alternatives.entries.map((row) => 'HealthCondition.${row.key.name}: {${row.value.entries.map((cell) => 'Preference.${cell.key.name}: ${_list(cell.value)}').join(', ')}}').join(', ')}}, '
    'healthConditions: {${f.healthConditions.map((c) => 'HealthCondition.${c.name}').join(', ')}}, '
    'personalPrefs: {${f.personalPrefs.map((p) => 'Preference.${p.name}').join(', ')}}, '
    'localNews: ${_string(f.localNews)}, '
    'generalInfo: ${_string(f.generalInfo)}, '
    'sources: ${_list(f.sources)}, '
    'nutrients: {${f.nutrients.entries.map((e) => 'Nutrient.${e.key.name}: ${e.value.toDouble()}').join(', ')}})';

/// A camelCase identifier for [id] (`bread_(toast)` → `breadToast`), unique
/// within [used].
String _identifier(String id, Set<String> used) {
  final words = id
      .split(RegExp(r'[^A-Za-z0-9]+'))
      .where((w) => w.isNotEmpty)
      .toList();
  var base = words.isEmpty
      ? 'food'
      : words.first +
            words
                .skip(1)
                .map((w) => w[0].toUpperCase() + w.substring(1))
                .join();
  if (RegExp(r'^[0-9]').hasMatch(base)) base = 'food$base';
  if (_reserved.contains(base)) base = '${base}Food';
  var name = base;
  for (var i = 2; !used.add(name); i++) {
    name = '$base$i';
  }
  return name;
}

String _list(List<String> items) => '[${items.map(_string).join(', ')}]';

/// A single-quoted Dart string literal for [s].
String _string(String s) =>
    "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$').replaceAll('\n', r'\n').replaceAll('\r', r'\r')}'";
