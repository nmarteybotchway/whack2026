/// Tesco rejected a request or returned an unexpected response.
class TescoException implements Exception {
  const TescoException(this.message, {this.statusCode});

  final String message;
  final int? statusCode;

  @override
  String toString() =>
      'TescoException${statusCode == null ? '' : ' ($statusCode)'}: $message';
}

/// A physical Tesco store from the store locator.
class TescoStore {
  const TescoStore({
    required this.branchNumber,
    required this.name,
    required this.format,
    required this.address,
    required this.postcode,
    required this.latitude,
    required this.longitude,
    required this.distanceMiles,
  });

  /// Tesco branch number (e.g. "2325"), used as the store id by Tesco APIs.
  final String branchNumber;
  final String name;

  /// Superstore, Extra, Express, Metro, ...
  final String? format;
  final String address;
  final String? postcode;
  final double? latitude;
  final double? longitude;
  final double? distanceMiles;

  /// Parses an entry of `assets/tesco_stores.json`.
  factory TescoStore.fromJson(Map<String, dynamic> json) => TescoStore(
    branchNumber: '${json['branchNumber']}',
    name: '${json['name'] ?? 'Tesco'}',
    format: json['format'] as String?,
    address: '${json['address'] ?? ''}',
    postcode: json['postcode'] as String?,
    latitude: (json['latitude'] as num?)?.toDouble(),
    longitude: (json['longitude'] as num?)?.toDouble(),
    distanceMiles: (json['distanceMiles'] as num?)?.toDouble(),
  );

  TescoStore _withDistance(double miles) => TescoStore(
    branchNumber: branchNumber,
    name: name,
    format: format,
    address: address,
    postcode: postcode,
    latitude: latitude,
    longitude: longitude,
    distanceMiles: miles,
  );

  Map<String, dynamic> toJson() => {
    'branchNumber': branchNumber,
    'name': name,
    'format': format,
    'address': address,
    'postcode': postcode,
    'latitude': latitude,
    'longitude': longitude,
    'distanceMiles': distanceMiles,
  };

  @override
  String toString() => '$name ($branchNumber)';
}

/// Offline snapshot of Tesco's UK stores, used to find the store nearest a
/// location.
///
/// tesco.com's store locator rejects Dart's HTTP client (Akamai TLS
/// fingerprinting), so the directory ships as `assets/tesco_stores.json`,
/// generated by `tool/fetch_tesco_stores.py`. In Flutter:
/// ```dart
/// final stores = TescoStoreDirectory.parse(
///   await rootBundle.loadString(TescoStoreDirectory.assetPath),
/// );
/// ```
class TescoStoreDirectory {
  TescoStoreDirectory(this.stores);

  static const assetPath = 'assets/tesco_stores.json';

  final List<TescoStore> stores;

  factory TescoStoreDirectory.parse(String json) {
    final decoded = jsonDecode(json);
    if (decoded is! List) {
      throw const FormatException('Expected a JSON list of stores.');
    }
    return TescoStoreDirectory([
      for (final s in decoded.cast<Map<String, dynamic>>())
        TescoStore.fromJson(s),
    ]);
  }

  /// Stores nearest to the given point, closest first, with
  /// [TescoStore.distanceMiles] filled in. [formats] (e.g. `{'Superstore',
  /// 'Extra'}`) restricts the store types considered.
  List<TescoStore> nearest(
    double latitude,
    double longitude, {
    int limit = 5,
    Set<String>? formats,
  }) {
    final ranked = [
      for (final store in stores)
        if (store.latitude != null &&
            store.longitude != null &&
            (formats == null || formats.contains(store.format)))
          store._withDistance(
            _haversineMiles(
              latitude,
              longitude,
              store.latitude!,
              store.longitude!,
            ),
          ),
    ]..sort((a, b) => a.distanceMiles!.compareTo(b.distanceMiles!));
    return ranked.take(limit).toList();
  }

  TescoStore? byBranch(String branchNumber) =>
      stores.where((s) => s.branchNumber == branchNumber).firstOrNull;

  static double _haversineMiles(
    double lat1,
    double lon1,
    double lat2,
    double lon2,
  ) {
    const earthRadiusMiles = 3958.8;
    double rad(double deg) => deg * math.pi / 180;
    final dLat = rad(lat2 - lat1);
    final dLon = rad(lon2 - lon1);
    final a =
        math.pow(math.sin(dLat / 2), 2) +
        math.cos(rad(lat1)) *
            math.cos(rad(lat2)) *
            math.pow(math.sin(dLon / 2), 2);
    return 2 * earthRadiusMiles * math.asin(math.sqrt(a));
  }
}

/// A department/aisle node from Tesco's category taxonomy.
class TescoCategory {
  const TescoCategory({
    required this.id,
    required this.name,
    this.children = const [],
  });

  /// Opaque facet id (e.g. "b;R3JvY2VyaWVz...") accepted by `category`.
  final String id;
  final String name;

  /// Aisles of a department (empty for aisles).
  final List<TescoCategory> children;

  factory TescoCategory.fromJson(Map<String, dynamic> json) => TescoCategory(
    id: '${json['id']}',
    name: '${json['name']}',
    children: [
      for (final child
          in (json['children'] as List? ?? const [])
              .cast<Map<String, dynamic>>())
        TescoCategory.fromJson(child),
    ],
  );
}

/// A product listing as returned by Tesco's category browse.
class TescoProduct {
  const TescoProduct({
    required this.id,
    required this.title,
    this.tpnb,
    this.gtin,
    this.brand,
    this.department,
    this.aisle,
    this.shelf,
    this.price,
    this.unitPrice,
    this.unitOfMeasure,
    this.imageUrl,
    this.foodIcons = const [],
    this.isForSale,
    this.isMarketplace = false,
  });

  /// TPNC: the id used by Tesco's product pages and [TescoApi.fetchDetails].
  final String id;
  final String title;
  final String? tpnb;

  /// Barcode (EAN/GTIN-14), useful for matching scanned products.
  final String? gtin;
  final String? brand;
  final String? department;
  final String? aisle;
  final String? shelf;
  final double? price;
  final double? unitPrice;
  final String? unitOfMeasure;
  final String? imageUrl;

  /// e.g. "Suitable for Vegans", "Suitable for Vegetarians".
  final List<String> foodIcons;
  final bool? isForSale;

  /// Sold and delivered by a third-party Marketplace seller, not stocked by
  /// Tesco stores.
  final bool isMarketplace;

  factory TescoProduct.fromJson(Map<String, dynamic> json) {
    final price = json['price'] as Map<String, dynamic>?;
    return TescoProduct(
      id: '${json['id']}',
      title: '${json['title'] ?? ''}',
      tpnb: json['tpnb'] as String?,
      gtin: json['gtin'] as String?,
      brand: json['brandName'] as String?,
      department: json['departmentName'] as String?,
      aisle: json['aisleName'] as String?,
      shelf: json['shelfName'] as String?,
      price: (price?['actual'] as num?)?.toDouble(),
      unitPrice: (price?['unitPrice'] as num?)?.toDouble(),
      unitOfMeasure: price?['unitOfMeasure'] as String?,
      imageUrl: json['defaultImageUrl'] as String?,
      foodIcons: [
        for (final icon in json['foodIcons'] as List? ?? const []) '$icon',
      ],
      isForSale: json['isForSale'] as bool?,
      isMarketplace:
          json['isMarketplace'] as bool? ??
          (json['__typename'] == 'MPProduct' ||
              json['superDepartmentName'] == 'Marketplace'),
    );
  }

  Map<String, dynamic> toJson() => {
    'id': id,
    'title': title,
    'tpnb': tpnb,
    'gtin': gtin,
    'brand': brand,
    'department': department,
    'aisle': aisle,
    'shelf': shelf,
    'price': price,
    'unitPrice': unitPrice,
    'unitOfMeasure': unitOfMeasure,
    'imageUrl': imageUrl,
    'foodIcons': foodIcons,
    'isForSale': isForSale,
    'isMarketplace': isMarketplace,
  };
}

/// Ingredients, allergens and nutrition for one product.
class TescoProductDetails {
  const TescoProductDetails({
    required this.id,
    required this.ingredients,
    required this.allergens,
    required this.nutrition,
  });

  final String id;

  /// Ingredient list; allergens are wrapped in `<strong>` tags by Tesco.
  final List<String> ingredients;

  /// Allergen statements, keyed by Tesco's heading (e.g. "Other Allergen Info").
  final Map<String, List<String>> allergens;

  /// Nutrition table rows. The first row is usually the header
  /// (e.g. `["Typical Values", "Per 100g", "Per Slice", ...]`).
  final List<List<String>> nutrition;

  factory TescoProductDetails.fromJson(Map<String, dynamic> json) {
    final details = json['details'] as Map<String, dynamic>? ?? const {};
    return TescoProductDetails(
      id: '${json['id']}',
      ingredients: [
        for (final i in details['ingredients'] as List? ?? const []) '$i',
      ],
      allergens: {
        for (final a
            in (details['allergens'] as List? ?? const [])
                .cast<Map<String, dynamic>>())
          '${a['name']}': [for (final v in a['values'] as List? ?? []) '$v'],
      },
      nutrition: [
        for (final row
            in (details['nutrition'] as List? ?? const [])
                .cast<Map<String, dynamic>>())
          [
            for (final key in ['name', 'value1', 'value2', 'value3', 'value4'])
              if (row[key] != null) '${row[key]}',
          ],
      ],
    );
  }

  Map<String, dynamic> toJson() => {
    'id': id,
    'ingredients': ingredients,
    'allergens': allergens,
    'nutrition': nutrition,
  };
}

/// Client for Tesco's public (unauthenticated) `xapi.tesco.com` GraphQL
/// gateway used by tesco.com/groceries, plus UK location geocoding.
///
/// These are undocumented website endpoints, not an official API, so they may
/// change without notice. Anonymous catalogue requests return Tesco's online
/// grocery range; Tesco does not expose a per-store in-store range publicly,
/// so [fetchFoodProducts] gives the range available for the chosen store's
/// area rather than a shelf-by-shelf stock list.
///
/// ```dart
/// final tesco = TescoApi();
/// final (lat, lng) = await tesco.geocode('CV4 7AL');
/// final store = directory.nearest(lat, lng).first;
/// final food = await tesco.fetchFoodProducts(storeId: store.branchNumber);
/// tesco.close();
/// ```
class TescoApi {
  TescoApi({
    http.Client? client,
    this.timeout = const Duration(seconds: 30),
    this.pageSize = 500,
    this.requestDelay = const Duration(milliseconds: 300),
    this.maxRetries = 4,
  }) : _client = client ?? http.Client(),
       _ownsClient = client == null;

  /// Public key embedded in tesco.com's web app.
  static const _xapiKey = 'TvOSZJHlEk0pjniDGQFAc9Q59WGAR4dA';
  static final _xapiUri = Uri.parse('https://xapi.tesco.com/');
  static const _userAgent =
      'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 '
      '(KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';

  /// Top-level groceries super-department containing all food departments.
  static const groceriesName = 'Groceries & Essentials';

  /// Departments under [groceriesName] that sell food and drink.
  static const defaultFoodDepartments = {
    'Fresh Food',
    'Bakery',
    'Frozen Food',
    'Treats & Snacks',
    'Food Cupboard',
    'Drinks',
  };

  final http.Client _client;
  final bool _ownsClient;
  final Duration timeout;

  /// Products per `category` page (Tesco accepts up to at least 500).
  final int pageSize;

  /// Pause between paginated requests, to stay under Tesco's rate limit.
  final Duration requestDelay;

  /// Retries (with exponential backoff) after "Too many requests".
  final int maxRetries;

  static final _latLng = RegExp(
    r'^\s*(-?\d+(?:\.\d+)?)\s*,\s*(-?\d+(?:\.\d+)?)\s*$',
  );

  /// Resolves a UK [location] (a `"lat,lng"` pair, postcode, or place name)
  /// to coordinates using postcodes.io (free, no key). Throws
  /// [TescoException] if it can't be found.
  Future<(double, double)> geocode(String location) async {
    final query = location.trim();
    if (query.isEmpty) throw ArgumentError('Location must not be empty.');
    final pair = _latLng.firstMatch(query);
    if (pair != null) {
      return (double.parse(pair[1]!), double.parse(pair[2]!));
    }

    Future<Map<String, dynamic>?> lookup(Uri uri) async {
      final response = await _client.get(uri).timeout(timeout);
      if (response.statusCode == 404) return null;
      if (response.statusCode != 200) {
        throw TescoException(
          'Geocoding request failed.',
          statusCode: response.statusCode,
        );
      }
      final result = _decodeObject(response, 'postcodes.io')['result'];
      if (result is List) {
        return result.isEmpty ? null : result.first as Map<String, dynamic>;
      }
      return result as Map<String, dynamic>?;
    }

    final place =
        await lookup(
          Uri.https(
            'api.postcodes.io',
            '/postcodes/${query.replaceAll('/', '')}',
          ),
        ) ??
        await lookup(
          Uri.https('api.postcodes.io', '/places', {'q': query, 'limit': '1'}),
        );
    final lat = (place?['latitude'] as num?)?.toDouble();
    final lng = (place?['longitude'] as num?)?.toDouble();
    if (lat == null || lng == null) {
      throw TescoException('Could not find location "$query".');
    }
    return (lat, lng);
  }

  /// Returns the food departments (and their ids) for [storeId].
  Future<List<TescoCategory>> fetchFoodDepartments({
    String? storeId,
    Set<String> departments = defaultFoodDepartments,
  }) async {
    final data = await _graphql(
      r'''
query Taxonomy($storeId: ID) {
  taxonomy(storeId: $storeId, includeInspirationEvents: false) {
    id name children { id name children { id name } }
  }
}''',
      {'storeId': storeId},
    );
    final roots = (data['taxonomy'] as List? ?? const [])
        .cast<Map<String, dynamic>>();
    final groceries = roots
        .where((r) => r['name'] == groceriesName)
        .firstOrNull;
    if (groceries == null) {
      throw const TescoException('Groceries department not found.');
    }
    return [
      for (final child
          in (groceries['children'] as List? ?? const [])
              .cast<Map<String, dynamic>>())
        if (departments.contains(child['name'])) TescoCategory.fromJson(child),
    ];
  }

  /// Tesco stops paginating a listing after this many results.
  static const resultCap = 10000;

  /// Fetches every product in one category, following pagination. Listings
  /// that hit [resultCap] are fetched aisle by aisle instead. Marketplace
  /// (third-party) items are dropped unless [includeMarketplace] is set.
  Future<List<TescoProduct>> fetchCategory(
    TescoCategory category, {
    bool includeMarketplace = false,
    void Function(int fetched, int total)? onProgress,
  }) async {
    final products = <String, TescoProduct>{};
    for (var page = 1; ; page++) {
      if (page > 1) await Future<void>.delayed(requestDelay);
      final data = await _graphql(_categoryQuery, {
        'facet': category.id,
        'page': page,
        'count': pageSize,
      });
      final listing = data['category'] as Map<String, dynamic>?;
      final total = (listing?['info']?['total'] as num?)?.toInt() ?? 0;
      final results = (listing?['results'] as List? ?? const [])
          .cast<Map<String, dynamic>>();
      if (page == 1 && total >= resultCap && category.children.isNotEmpty) {
        return _fetchChildren(category, includeMarketplace, onProgress);
      }
      var added = 0;
      for (final result in results) {
        final node = result['node'] as Map<String, dynamic>?;
        if (node == null || node['id'] == null) continue;
        // Pages include a few sponsored repeats; keep the first copy.
        if (products.containsKey('${node['id']}')) continue;
        products['${node['id']}'] = TescoProduct.fromJson(node);
        added++;
      }
      onProgress?.call(products.length, total);
      if (results.isEmpty || added == 0 || products.length >= total) break;
    }
    return [
      for (final p in products.values)
        if (includeMarketplace || !p.isMarketplace) p,
    ];
  }

  Future<List<TescoProduct>> _fetchChildren(
    TescoCategory category,
    bool includeMarketplace,
    void Function(int fetched, int total)? onProgress,
  ) async {
    final products = <String, TescoProduct>{};
    for (final child in category.children) {
      await Future<void>.delayed(requestDelay);
      final items = await fetchCategory(
        child,
        includeMarketplace: includeMarketplace,
      );
      for (final p in items) {
        products.putIfAbsent(p.id, () => p);
      }
      onProgress?.call(products.length, products.length);
    }
    return products.values.toList();
  }

  /// Fetches all food and drink products for [storeId] (see class docs for
  /// what "for a store" means here). Products are de-duplicated across
  /// departments.
  Future<List<TescoProduct>> fetchFoodProducts({
    String? storeId,
    Set<String> departments = defaultFoodDepartments,
    bool includeMarketplace = false,
    void Function(String department, int fetched, int total)? onProgress,
  }) async {
    final categories = await fetchFoodDepartments(
      storeId: storeId,
      departments: departments,
    );
    final products = <String, TescoProduct>{};
    for (final category in categories) {
      await Future<void>.delayed(requestDelay);
      final items = await fetchCategory(
        category,
        includeMarketplace: includeMarketplace,
        onProgress: (fetched, total) =>
            onProgress?.call(category.name, fetched, total),
      );
      for (final p in items) {
        products.putIfAbsent(p.id, () => p);
      }
    }
    return products.values.toList();
  }

  /// Ingredients, allergens and nutrition for one product, by TPNC
  /// ([TescoProduct.id]). Returns null if Tesco doesn't know the product.
  Future<TescoProductDetails?> fetchDetails(String productId) async {
    final Map<String, dynamic> data;
    try {
      data = await _graphql(
        r'''
query Product($tpnc: String) {
  product(tpnc: $tpnc) {
    id
    details {
      ingredients
      allergens { name values }
      nutrition { name value1 value2 value3 value4 }
    }
  }
}''',
        {'tpnc': productId},
      );
    } on TescoException catch (e) {
      if (e.statusCode == 404) return null;
      rethrow;
    }
    final product = data['product'] as Map<String, dynamic>?;
    return product == null ? null : TescoProductDetails.fromJson(product);
  }

  /// Closes the HTTP client if this instance created it.
  void close() {
    if (_ownsClient) _client.close();
  }

  static const _categoryQuery = r'''
query Category($facet: ID, $page: Int, $count: Int) {
  category(facet: $facet, page: $page, count: $count) {
    info { total page count pageSize offset }
    results {
      node {
        ... on ProductInterface {
          __typename id tpnb gtin title brandName
          superDepartmentName departmentName aisleName shelfName
          isForSale defaultImageUrl foodIcons
          price { actual unitPrice unitOfMeasure }
        }
      }
    }
  }
}''';

  Future<Map<String, dynamic>> _graphql(
    String query,
    Map<String, dynamic> variables,
  ) async {
    for (var attempt = 0; ; attempt++) {
      final response = await _client
          .post(
            _xapiUri,
            headers: {
              'content-type': 'application/json',
              'accept': 'application/json',
              'x-apikey': _xapiKey,
              'region': 'UK',
              'language': 'en-GB',
              'user-agent': _userAgent,
            },
            body: jsonEncode({'query': query, 'variables': variables}),
          )
          .timeout(timeout);

      final body = response.statusCode == 429
          ? null
          : _decodeObject(response, 'Tesco GraphQL');
      final errors = (body?['errors'] as List? ?? const [])
          .cast<Map<String, dynamic>>();
      final rateLimited =
          response.statusCode == 429 ||
          errors.any((e) => '${e['message']}'.contains('Too many requests'));
      if (rateLimited) {
        if (attempt >= maxRetries) {
          throw const TescoException('Rate limited by Tesco.', statusCode: 429);
        }
        await Future<void>.delayed(Duration(seconds: 2 << attempt));
        continue;
      }
      if (errors.isNotEmpty) {
        final first = errors.first;
        final status =
            (first['extensions']?['http']?['status'] as num?)?.toInt() ??
            (body?['status'] as num?)?.toInt();
        throw TescoException('${first['message']}', statusCode: status);
      }
      final data = body?['data'];
      if (data is! Map<String, dynamic>) {
        throw TescoException(
          'Tesco GraphQL returned no data.',
          statusCode: response.statusCode,
        );
      }
      return data;
    }
  }

  static Map<String, dynamic> _decodeObject(
    http.Response response,
    String source,
  ) {
    final dynamic body;
    try {
      body = jsonDecode(utf8.decode(response.bodyBytes));
    } on FormatException {
      throw TescoException(
        '$source returned invalid JSON.',
        statusCode: response.statusCode,
      );
    }
    if (body is! Map<String, dynamic>) {
      throw TescoException(
        '$source returned an unexpected JSON format.',
        statusCode: response.statusCode,
      );
    }
    return body;
  }
}
